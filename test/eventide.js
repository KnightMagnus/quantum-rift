// Authored v2.9 topology, old-save compatibility and normal mission lifecycle.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { SYSTEMS, SYS, STELLARS } from '../shared/galaxy.js';
import { EVENTIDE, EVENTIDE_LINKS, eventideDrain, eventidePulse } from '../shared/eventide.js';
import { Game } from '../server/game.js';
import { DT } from '../shared/rules.js';
import { DB } from '../server/db.js';

const ids = new Set(EVENTIDE.map((s) => s.id));
assert.equal(SYSTEMS.length, 217);
assert.equal(ids.size, 6);
assert.equal(new Set(SYSTEMS.map((s) => s.id)).size, SYSTEMS.length);
assert.equal(
  new Set(SYSTEMS.flatMap((s) => s.stellars.map((p) => p.id))).size,
  Object.keys(STELLARS).length,
);
// Golden source: untouched v2.8.3 generation, normalized ONLY for approved Terra text.
// Scenes and the one new Vesper branch are additions; every legacy generated property stays exact.
const legacy = JSON.parse(JSON.stringify(SYSTEMS.filter((s) => !s.eventide)));
for (const s of legacy) {
  delete s.scene;
  // Mining3.0 intentionally adds only four processed-good price entries; compare
  // every legacy property/price exactly against the existing generation golden.
  for (const p of s.stellars)
    for (const id of [
      'alloy_ingots',
      'fuel_cells',
      'cut_crystal',
      'composite_plating',
      'plasma',
      'quantum_fuel',
      'exotic_matter',
    ])
      if (p.prices) delete p.prices[id];
  // v2.9.2 deliberately moves only the Far Gateway; preserve the generation golden.
  for (const p of s.stellars)
    if (p.id === 'coldharbor-gate') {
      p.x = 600;
      p.y = 600;
    }
  s.links = s.links.filter((id) => !ids.has(id));
}
for (const sys of Object.values(legacy))
  if (sys.fields) sys.fields = sys.fields.filter((f) => !f.industrial);
assert.equal(
  createHash('sha256').update(JSON.stringify(legacy)).digest('hex'),
  '2eb244aab8a9987f780b6bd0fc318ee7845e716351369fd4602a9336ce0bee25',
);
for (const [a, b] of EVENTIDE_LINKS) {
  assert.ok(SYS[a].links.includes(b));
  assert.ok(SYS[b].links.includes(a));
}
const reached = new Set(['vesper-gate']),
  queue = ['vesper-gate'];
while (queue.length)
  for (const n of SYS[queue.shift()].links)
    if (!reached.has(n)) {
      reached.add(n);
      queue.push(n);
    }
for (const e of EVENTIDE) {
  assert.ok(reached.has(e.id));
  assert.ok(STELLARS[e.port.id]);
  assert.ok(e.port.svc.includes('B'));
  assert.ok(e.port.svc.includes('L'));
  assert.ok(SYS[e.id].farside);
}
const h = SYS.reliquary.scene.hazard;
assert.equal(eventidePulse(h, 0), 'active');
assert.equal(eventidePulse(h, 4), 'quiet');
assert.equal(eventidePulse(h, 15), 'warning');
assert.equal(eventidePulse(h, 18), 'active');
assert.equal(eventideDrain(SYS.reliquary, { state: 'fly', x: h.x, y: h.y }, 1), 24);
assert.equal(eventideDrain(SYS.reliquary, { state: 'fly', x: h.x, y: h.y }, 10), 0);
for (const p of SYS.reliquary.stellars)
  assert.ok(
    Math.hypot(p.x - h.x, p.y - h.y) > h.r + p.r + 200,
    'stable ports outside radiation pocket',
  );
for (const id of ['meridian', 'gloam', 'slagforge'])
  assert.ok(SYS[id].scene, 'authored main-galaxy scenery');

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'rift-eventide-'));
try {
  const A = JSON.parse(fs.readFileSync(new URL('../shared/assets.json', import.meta.url))),
    db = new DB(dir),
    game = new Game(A, db);
  const d = game.fresh();
  d.name = 'Eventide Regression';
  d.tut = 999;
  d.credits = 1000000;
  const s = { id: 9876, name: d.name, data: d, sock: { open: true, backlog: 0, send: () => {} } };
  game.sessions.set(s.id, s);
  const lifecycle = [];
  for (const E of EVENTIDE) {
    d.sys = E.id;
    d.stellar = E.port.id;
    const offers = game.offers(STELLARS[d.stellar], d),
      supply = offers.find((o) => o.id.startsWith('eventide-') && o.type === 'cargo'),
      rescue = offers.find((o) => o.id.startsWith('eventide-') && o.type === 'rescue');
    assert.ok(supply && rescue, E.id + ' has supply and rescue work');
    assert.notEqual(supply.dest, d.stellar);
    game.accept(s, supply.id);
    assert.ok(
      d.missions.some((m) => m.id === supply.id),
      'authoritative board accepts cargo',
    );
    db.create(d.name, 'test', d);
    db.flush();
    const saved = new DB(dir).get(d.name);
    assert.equal(saved.missions.find((m) => m.id === supply.id).dest, supply.dest);
    const credits = d.credits;
    d.sys = supply.sys;
    d.stellar = supply.dest;
    game.completeOnLanding(s, STELLARS[supply.dest]);
    assert.ok(!d.missions.some((m) => m.id === supply.id));
    assert.ok(d.credits >= credits + supply.reward);
    // Survey stages remain generated by the existing expedition loop; persisted stages keep their references.
    d.sys = E.id;
    d.stellar = E.port.id;
    const exp = game.features.arcs.expeditionOffer(STELLARS[d.stellar], d);
    assert.ok(ids.has(exp.sys));
    assert.ok(ids.has(exp.exp.b));
    d.missions.push({ ...exp, done: true, owner: s.id });
    game.completeOnLanding(s, STELLARS[d.stellar]);
    const stage2 = d.missions.find((m) => m.exp?.stage === 2);
    assert.ok(stage2);
    assert.ok(ids.has(stage2.sys));
    db.create(d.name, 'test', d);
    db.flush();
    assert.equal(new DB(dir).get(d.name).missions.find((m) => m.exp?.stage === 2).sys, stage2.sys);
    stage2.done = true;
    game.completeOnLanding(s, STELLARS[d.stellar]);
    const ret = d.missions.find((m) => m.exp?.stage === 3);
    if (ret) game.completeOnLanding(s, STELLARS[ret.dest]);
    assert.equal(d.expd.n, lifecycle.length + 1);
    assert.ok(d.missions.every((m) => !m.exp));
    lifecycle.push({ system: E.id, supply: supply.id, expedition: d.expd.n });
  }
  // Authored rescue uses the normal disabled-ship spawn/boarding/payment path.
  d.sys = 'lantern-twins';
  d.stellar = 'twins-exchange';
  const rescue = game.offers(STELLARS[d.stellar], d).find((m) => m.eventide && m.type === 'rescue');
  game.accept(s, rescue.id);
  d.sys = rescue.sys;
  d.stellar = null;
  game.spawnPlayer(s, -1100, 900, 0, 0);
  const rescueSpace = game.spaces[d.sys];
  game.features.fronts.missionArrive(s, rescueSpace);
  const wreck = [...rescueSpace.ships.values()].find((e) => e.rescueOf?.id === rescue.id);
  assert.ok(wreck?.disabled);
  assert.deepEqual([wreck.x, wreck.y], rescue.rescuePoint);
  s.ent.x = wreck.x + 30;
  s.ent.y = wreck.y;
  s.ent.vx = wreck.vx;
  s.ent.vy = wreck.vy;
  game.features.hangar.board(s, { id: wreck.id, act: 'rescue' });
  assert.ok(
    d.missions.find((m) => m.id === rescue.id).done,
    'real boarding completes authored rescue',
  );
  const paidAt = SYS[d.sys].stellars.find((p) => p.svc.includes('L'));
  rescueSpace.remove(s.ent);
  s.ent = null;
  d.stellar = paidAt.id;
  const rescueCredits = d.credits;
  game.completeOnLanding(s, STELLARS[paidAt.id]);
  assert.ok(d.credits >= rescueCredits + rescue.reward);
  assert.ok(!d.missions.some((m) => m.id === rescue.id));
  // Actual live simulation applies bounded environmental shield drain, never hull damage.
  d.sys = 'reliquary';
  d.stellar = null;
  game.spawnPlayer(s, h.x, h.y, 0, 0);
  const pulseSpace = game.spaces.reliquary;
  for (const e of [...pulseSpace.ships.values()]) if (e !== s.ent) pulseSpace.remove(e);
  pulseSpace.spawnT = 9999;
  const e = s.ent;
  e.x = h.x;
  e.y = h.y;
  e.vx = e.vy = 0;
  e.st.shieldRe = 0;
  const wallNow = Date.now;
  try {
    Date.now = () => 18000;
    e.shield = 35;
    const armor = e.armor;
    pulseSpace.tick();
    assert.ok(Math.abs(e.shield - (35 - 24 * DT)) < 1e-8);
    e.shield = 0;
    pulseSpace.tick();
    assert.equal(e.armor, armor);
    Date.now = () => 25000;
    e.shield = 35;
    pulseSpace.tick();
    assert.equal(e.shield, 35);
  } finally {
    Date.now = wallNow;
  }
  pulseSpace.remove(e);
  s.ent = null;
  // Existing save counts still select the same original ten-system expeditions.
  d.sys = 'coldharbor';
  d.stellar = SYS.coldharbor.stellars[0].id;
  d.expd.n = 0;
  const old = game.features.arcs.expeditionOffer(STELLARS[d.stellar], d);
  assert.equal(old.sys, 'mirrorfall');
  assert.equal(old.exp.b, 'quietude');
  console.log(
    JSON.stringify(
      {
        systems: SYSTEMS.length,
        legacyStable: true,
        lifecycle,
        hazard: 'bounded shield-only, safe docks',
      },
      null,
      2,
    ),
  );
} finally {
  fs.rmSync(dir, { recursive: true, force: true });
}

process.exit(0);
