// Each of the eleven stores offers a signature weapon, a defence or drive part, and a utility.
import type { OutfitAsset, WeaponAsset } from './rules.ts';

/** Standing tiers for the three store outfit slots. */
export const STORE_OUTFIT_STANDING = { utility: 30, defence: 45, weapon: 60 } as const;

/** A store-only outfit with the store listing details it needs. */
export interface FactionStoreOutfit extends OutfitAsset {
  /** Selling faction; the outfit appears only in that faction's store. */
  faction: string;
  /** Faction tokens charged on top of the credit price. */
  tokens: number;
  /** Minimum standing with the selling faction. */
  rep: number;
  /** Never stocked by an outfitter; bought from the faction store only. */
  storeOnly: true;
}

/** Shared weapon fields; projectiles, beams and sounds reuse existing rendering. */
