import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Eta } from 'eta';
import { format } from 'oxfmt';

const root = fileURLToPath(new URL('../', import.meta.url));
const compiler = new Eta({ useWith: false, autoTrim: false, debug: false });

/** Compile interpolation-only views; composition stays in typed application code. */
export async function generateTemplates(check = false) {
  const directory = path.join(root, 'client/templates');
  const manifest = JSON.parse(fs.readFileSync(path.join(directory, 'manifest.json'), 'utf8')) as {
    name: string;
    source: string;
    line: number;
    slots: { name: string; escaped: boolean; doubleQuoted?: boolean; policy: string }[];
  }[];
  let output = '// Generated by tools/eta-generate.ts; edit client/templates/*.eta instead.\n';
  output += "import { escapeHtml, escapeDoubleQuotedHtml } from './html.ts';\n";
  output += "import type { HtmlValue } from './html.ts';\n";
  output += "import type { LegacyHtmlFragment } from './eta-runtime.ts';\n";
  const names = new Set<string>();
  for (const template of manifest) {
    if (!/^render[A-Za-z0-9_$]+$/.test(template.name) || names.has(template.name))
      throw new Error('Invalid or duplicate Eta template name: ' + template.name);
    names.add(template.name);
    const slots = new Set<string>();
    for (const slot of template.slots) {
      if (!/^[A-Za-z_$][\w$]*$/.test(slot.name) || slots.has(slot.name) || !slot.policy)
        throw new Error('Invalid or undocumented Eta slot: ' + template.name + '.' + slot.name);
      slots.add(slot.name);
    }
    const source = fs.readFileSync(path.join(directory, template.name + '.eta'), 'utf8');
    if (/<%/.test(source.replace(/<%[=~] it\.[A-Za-z_$][\w$]* %>/g, '')))
      throw new Error('Executable Eta tags are not allowed: ' + template.name);
    const interpolations = [...source.matchAll(/<%([=~]) it\.([A-Za-z_$][\w$]*) %>/g)];
    if (
      interpolations.length !== template.slots.length ||
      interpolations.some(
        (match, index) =>
          match[2] !== template.slots[index].name ||
          (match[1] === '=') !== template.slots[index].escaped,
      )
    )
      throw new Error('Eta source/model slot mismatch: ' + template.name);
    // Eta 4.6 compileToString includes layout/include closures. Views deliberately
    // disallow those: compileBody(parse(source)) emits only static appends.
    let body = compiler.compileBody(compiler.parse(source));
    for (const slot of template.slots)
      if (slot.doubleQuoted)
        body = body.replaceAll('__eta.e(it.' + slot.name + ')', '__eta.q(it.' + slot.name + ')');
    output +=
      '\n/** Precompiled ' +
      template.source +
      ':' +
      template.line +
      '; raw fields preserve audited legacy interpolation. */\nexport function ' +
      template.name +
      '(' +
      (template.slots.length
        ? 'it: { ' +
          template.slots
            .map(
              (slot) =>
                '/** ' +
                slot.policy.replaceAll('*/', '* /') +
                ' */ ' +
                slot.name +
                ': ' +
                (slot.escaped ? 'HtmlValue' : 'LegacyHtmlFragment'),
            )
            .join('; ') +
          ' }'
        : '') +
      '): string {\n';
    output +=
      'const __eta = { res: "", e: escapeHtml, q: escapeDoubleQuotedHtml };\n' +
      body +
      '\nreturn __eta.res;\n}\n';
  }
  const target = path.join(root, 'client/eta-templates.ts');
  const formatted = await format(target, output, {
    singleQuote: true,
    printWidth: 100,
    sortImports: false,
  });
  if (formatted.errors.length) throw new Error(JSON.stringify(formatted.errors));
  output = formatted.code;
  if (check) {
    if (fs.readFileSync(target, 'utf8') !== output)
      throw new Error('Generated Eta templates are stale');
  } else if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output)
    fs.writeFileSync(target, output);
  return manifest.length;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  console.log(
    'Eta: ' + (await generateTemplates(process.argv.includes('--check'))) + ' static templates.',
  );
